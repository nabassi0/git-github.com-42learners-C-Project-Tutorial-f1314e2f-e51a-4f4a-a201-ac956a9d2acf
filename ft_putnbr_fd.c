#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	long	l;
	char	a;

	l = n;
	if (l < 0)
	{
		write(fd, '-', 1);
		l *= -1;
	}
	if (l >= 10)
		ft_putnbr_fd((n / 10), fd);
	a = (n % 10) + '0';
	write (fd, &a, 1);
}
